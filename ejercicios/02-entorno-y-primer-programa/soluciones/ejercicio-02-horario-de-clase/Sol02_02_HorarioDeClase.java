public class Sol02_02_HorarioDeClase {

    public static void main(String[] args) {

        // Bloque 1: \n separa las líneas y \t las columnas.
        // "Lengua" es corto, por eso lleva dos \t para alinear la columna "Aula".
        System.out.println("HORARIO DEL LUNES\nHora\tAsignatura\tAula\n08:00\tMatemáticas\tA-12\n09:00\tLengua\t\tA-12\n10:00\tProgramación\tLAB-3");

        // Bloque 2: el \n inicial deja una línea en blanco; \" pinta comillas.
        System.out.println("\nRecuerda: \"Sin código no hay recreo\"");

        // Bloque 3: cada \\ se muestra como una sola barra.
        System.out.println("Apuntes en: C:\\Clase\\Programacion\\Tema02");
    }
}
